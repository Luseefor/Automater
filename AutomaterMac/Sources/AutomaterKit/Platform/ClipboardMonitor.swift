import AppKit
import Combine

@MainActor
public final class ClipboardMonitor: ObservableObject {
    @Published public var history: ClipboardHistory
    @Published public var selectedID: String?
    @Published public var isPaused: Bool {
        didSet { preferences.set(isPaused, forKey: "clipboard.paused"); lastChange = pasteboard.changeCount }
    }
    @Published public var error: String?
    private let pasteboard: NSPasteboard
    private let repository: ClipboardRepository
    private let preferences: UserDefaults
    private let now: () -> Date
    private var lastChange = -1
    private var cancellables = Set<AnyCancellable>()
    private var saveAllowed = true
    private let excludedTypes = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"]
    @Published public var limit: Int {
        didSet {
            let clamped = min(1000, max(1, limit))
            if limit != clamped { limit = clamped; return }
            preferences.set(limit, forKey: "clipboard.limit")
            applyRetention()
        }
    }
    @Published public var expiration: ClipboardExpiration {
        didSet {
            preferences.set(expiration.rawValue, forKey: "clipboard.expiration")
            applyRetention()
        }
    }

    public init(pasteboard: NSPasteboard = .general, repository: ClipboardRepository = ClipboardRepository(), preferences: UserDefaults = .standard, automaticallyPoll: Bool = true, now: @escaping () -> Date = Date.init) {
        self.pasteboard = pasteboard; self.repository = repository; self.preferences = preferences
        self.now = now
        limit = preferences.object(forKey: "clipboard.limit") == nil ? 100 : min(1000, max(1, preferences.integer(forKey: "clipboard.limit")))
        expiration = ClipboardExpiration(rawValue: preferences.integer(forKey: "clipboard.expiration")) ?? .never
        isPaused = preferences.bool(forKey: "clipboard.paused")
        do { history = try repository.load() }
        catch { history = ClipboardHistory(); saveAllowed = false; self.error = "Clipboard history couldn’t be read. The saved file has been preserved. \(error.localizedDescription)" }
        selectedID = history.entries.first?.id
        applyRetention()
        if automaticallyPoll {
            Timer.publish(every: 0.2, on: .main, in: .common).autoconnect().sink { [weak self] _ in self?.poll() }.store(in: &cancellables)
        }
        $history.dropFirst().debounce(for: .milliseconds(250), scheduler: RunLoop.main)
            .sink { [weak self] _ in self?.save() }.store(in: &cancellables)
        NotificationCenter.default.publisher(for: NSApplication.willTerminateNotification)
            .sink { [weak self] _ in self?.save() }.store(in: &cancellables)
    }
    public func poll() {
        if expiration != .never { applyRetention() }
        guard !isPaused, saveAllowed, pasteboard.changeCount != lastChange else { return }
        let capturedChange = pasteboard.changeCount
        lastChange = capturedChange
        let types = Set((pasteboard.types ?? []).map(\.rawValue))
        guard excludedTypes.allSatisfy({ !types.contains($0) }) else { return }
        let source = NSWorkspace.shared.frontmostApplication
        let sourceName = source?.localizedName ?? ""
        let bundle = source?.bundleIdentifier
        var entry: ClipboardEntry?
        var image: Data?
        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            entry = ClipboardEntry(kind: .files, paths: urls.map(\.path), copiedAt: now(), sourceName: sourceName, sourceBundleID: bundle)
        } else if let text = pasteboard.string(forType: .string), !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            guard text.utf8.count <= 500_000 else { return }
            entry = ClipboardEntry(text: text, copiedAt: now(), sourceName: sourceName, sourceBundleID: bundle)
        } else if let data = pasteboard.data(forType: .png), data.count <= 8_000_000 {
            image = data; entry = ClipboardEntry(kind: .image, imageData: data, copiedAt: now(), sourceName: sourceName, sourceBundleID: bundle)
        } else if let data = pasteboard.data(forType: .tiff), data.count <= 16_000_000,
                  let bitmap = NSBitmapImageRep(data: data), let png = bitmap.representation(using: .png, properties: [:]), png.count <= 8_000_000 {
            image = png; entry = ClipboardEntry(kind: .image, imageData: png, copiedAt: now(), sourceName: sourceName, sourceBundleID: bundle)
        }
        guard let entry else { return }
        guard pasteboard.changeCount == capturedChange else { lastChange = -1; return }
        if let image {
            do { try repository.saveImage(image, for: entry) }
            catch { self.error = "Couldn’t save the copied image: \(error.localizedDescription)"; return }
        }
        history.insert(entry, limit: limit)
        if selectedID == nil { selectedID = entry.id }
        if !history.entries.contains(where: { $0.id == selectedID }) { selectedID = entry.id }
    }
    public func copy(_ entry: ClipboardEntry) throws {
        switch entry.kind {
        case .text:
            pasteboard.clearContents()
            guard pasteboard.setString(entry.text, forType: .string) else { throw ClipboardError("Couldn’t update the clipboard. Try again.") }
        case .files:
            pasteboard.clearContents()
            guard pasteboard.writeObjects(entry.paths.map { NSURL(fileURLWithPath: $0) }) else { throw ClipboardError("Couldn’t copy these file references.") }
        case .image:
            guard let url = repository.imageURL(for: entry), let data = try? Data(contentsOf: url) else { throw ClipboardError("The saved image is no longer available.") }
            pasteboard.clearContents()
            guard pasteboard.setData(data, forType: .png) else { throw ClipboardError("Couldn’t copy this image.") }
        }
        lastChange = pasteboard.changeCount
    }
    public func togglePin(_ entry: ClipboardEntry) {
        guard let index = history.entries.firstIndex(where: { $0.id == entry.id }) else { return }
        if !entry.isPinned, history.entries.filter(\.isPinned).count >= 30 { error = "You can pin up to 30 clipboard items."; return }
        history.entries[index].isPinned.toggle()
        applyRetention()
    }
    public func remove(_ entry: ClipboardEntry) {
        history.entries.removeAll { $0.id == entry.id }
        if selectedID == entry.id { selectedID = history.entries.first?.id }
        save()
    }
    public func clear(keepingPinned: Bool) { history.clear(keepingPinned: keepingPinned); selectedID = history.entries.first?.id; save() }
    public func imageURL(for entry: ClipboardEntry) -> URL? { repository.imageURL(for: entry) }
    public func applyRetention() {
        guard saveAllowed else { return }
        var retained = history
        retained.applyRetention(limit: limit, maxAge: expiration.maxAge, now: now())
        guard retained != history else { return }
        history = retained
        if !history.entries.contains(where: { $0.id == selectedID }) { selectedID = history.entries.first?.id }
        save()
    }
    public func save() {
        guard saveAllowed else { return }
        do { try repository.save(history); try repository.pruneImages(keeping: history) }
        catch { self.error = "Couldn’t save clipboard history: \(error.localizedDescription)" }
    }
}
